/**
 * Approximate weightage (in % of its subject's section) for one chapter, or
 * null when no static entry exists. JEE Advanced shares JEE Main's map.
 */
export function chapterWeightage(
  examId: string | null | undefined,
  subject: string,
  chapter: string,
): number | null {
  if (!examId) return null;
  const id = examId === 'jee-advanced' ? 'jee' : examId;
  const value = CHAPTER_WEIGHTAGE[id]?.[subject]?.[chapter];
  return typeof value === 'number' ? value : null;
}
