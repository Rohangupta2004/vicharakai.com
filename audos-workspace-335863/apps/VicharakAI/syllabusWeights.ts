/**
 * Returns priority score for a chapter.
 * Heavy backlog (>= HEAVY_BACKLOG_THRESHOLD pending tasks): use expected question count.
 * Light backlog: equal weight (1.0) — no bias.
 */
export function getPriorityScore(
  examId: string,
  chapterName: string,
  pendingTaskCount: number
): number {
  if (pendingTaskCount < HEAVY_BACKLOG_THRESHOLD) return 1.0;
  const resolvedExamId = examId === 'neet' ? 'neet_ug' : examId === 'jee' ? 'jee_main' : examId;
  const examWeights = SYLLABUS_WEIGHTS[resolvedExamId];
  if (!examWeights) return 1.0;
  // Exact match first
  if (examWeights[chapterName] !== undefined) return examWeights[chapterName];
  // Fuzzy: case-insensitive substring match
  const key = Object.keys(examWeights).find(
    k => k.toLowerCase().includes(chapterName.toLowerCase()) ||
         chapterName.toLowerCase().includes(k.toLowerCase())
  );
  return key ? examWeights[key] : 1.0;
}
